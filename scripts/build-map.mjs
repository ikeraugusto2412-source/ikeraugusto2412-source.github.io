/*
 * Builds the land outline for the Works map (src/data/mapLand.js) from Natural Earth 1:110m land
 * (public domain), as published by the world-atlas package:
 *   curl -o land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json
 *   node scripts/build-map.mjs land-110m.json
 * Only the region the map shows is kept, already projected, so the site loads nothing extra.
 */
import { readFileSync, writeFileSync } from 'node:fs';

// Visible region (lon/lat) — New York on the left, Norway top right
export const VIEW = { lon0: -80, lon1: 25, lat0: 30, lat1: 66, width: 1000, squash: 0.78 };
const H = Math.round((VIEW.width * (VIEW.lat1 - VIEW.lat0)) / (VIEW.lon1 - VIEW.lon0) / VIEW.squash);
const proj = ([lon, lat]) => [((lon - VIEW.lon0) / (VIEW.lon1 - VIEW.lon0)) * VIEW.width, ((VIEW.lat1 - lat) / (VIEW.lat1 - VIEW.lat0)) * H];
const inView = ([lon, lat]) => lon > VIEW.lon0 - 15 && lon < VIEW.lon1 + 15 && lat > VIEW.lat0 - 10 && lat < VIEW.lat1 + 10;

const topo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
const ring = (ids) => ids.flatMap((id, k) => {
  const pts = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
  return k ? pts.slice(1) : pts;
});
const geoms = Object.values(topo.objects)[0].geometries;
const rings = geoms
  .flatMap((g) => (g.type === 'Polygon' ? [g.arcs] : g.arcs))
  .flatMap((poly) => poly.map(ring))
  .filter((pts) => pts.some(inView));
const d = rings
  .map((pts) => 'M' + pts.map((p) => proj(p).map((v) => Math.round(v * 10) / 10).join(',')).join('L') + 'Z')
  .join('');

writeFileSync(
  'src/data/mapLand.js',
  `// Generated by scripts/build-map.mjs from Natural Earth 1:110m land (public domain). Do not edit.\n` +
    `export const MAP_VIEW = ${JSON.stringify({ ...VIEW, height: H })};\n` +
    `export const MAP_LAND = '${d}';\n`,
);
console.log(`${rings.length} rings, ${(d.length / 1024).toFixed(1)} KB`);
